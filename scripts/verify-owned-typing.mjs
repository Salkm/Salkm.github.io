import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const output = 'artifacts/identity-study/typing';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const results = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [], requests = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => requests.push(r.url()));
  await page.goto(process.env.PORTFOLIO_URL || 'http://127.0.0.1:4175/', { waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => window.__portfolioScene?.getDiagnostics().motionSource === 'video', null, { timeout: 90000 });
  const state = () => page.evaluate(() => window.__portfolioScene.getDiagnostics());
  const initial = await state();
  assert.equal(initial.videoSource, '/portrait-typing.mp4');
  assert.deepEqual(initial.sourceSize, { width: 1280, height: 720 });
  assert.ok(Math.abs(initial.videoFraming.width / initial.videoFraming.height - 16/9) < .001, 'No aspect stretching');
  await page.waitForFunction(() => {
    const time = window.__portfolioScene.getDiagnostics().videoTime;
    const previous = window.__lastTypingTime;
    window.__lastTypingTime = time;
    return previous !== undefined && previous > 3 && time < 1;
  }, null, { polling: 150, timeout: 15000 });
  await page.getByRole('button', { name: 'Pause animation', exact: true }).click();
  const paused = await state();
  await page.waitForTimeout(450);
  assert.equal((await state()).videoTime, paused.videoTime, 'Pause stops the media clock');
  assert.equal(paused.videoPaused, true);
  await page.screenshot({ path: `${output}/desktop.png`, timeout: 90000 });
  await page.getByRole('button', { name: 'Play animation', exact: true }).click();
  await page.waitForFunction(t => window.__portfolioScene.getDiagnostics().videoTime !== t, paused.videoTime, { timeout: 10000 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.waitForFunction(() => window.__portfolioScene.getDiagnostics().motionSource === 'image');
  assert.equal((await state()).videoPaused, true);
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.waitForFunction(() => window.__portfolioScene.getDiagnostics().motionSource === 'video');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => window.__portfolioScene.getDiagnostics().mobile && window.__portfolioScene.getDiagnostics().motionSource === 'image');
  assert.equal((await state()).videoPaused, true, 'Mobile stops desktop media playback');
  await page.screenshot({ path: `${output}/mobile.png`, timeout: 90000 });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.waitForFunction(() => window.__portfolioScene.getDiagnostics().motionSource === 'video');
  await page.addStyleTag({ content: 'html{scroll-behavior:auto!important}' });
  await page.evaluate(() => scrollTo(0, 2100));
  await page.waitForFunction(() => !window.__portfolioScene.getDiagnostics().intersecting);
  assert.equal((await state()).videoPaused, true, 'Offscreen video pauses');
  await page.evaluate(() => scrollTo(0, 0));
  await page.waitForFunction(() => !window.__portfolioScene.getDiagnostics().videoPaused);
  assert.equal(requests.some(url => url.includes('/__reference-study/')), false);
  assert.deepEqual(errors, []);
  results.push({ initial, loopPassed: true, pausePassed: true, reducedMotionPassed: true, responsivePassed: true, offscreenPassed: true, errors });
  console.log('Owned typing: loop, pause/resume, aspect, reduced motion, mobile and offscreen playback passed');
} finally {
  await writeFile(`${output}/verification.json`, JSON.stringify(results, null, 2));
  await browser.close();
}
